def git_state(root: Path) -> dict:
    return {
        "head": git(root, "rev-parse", "HEAD").strip(),
        "parents": git(root, "show", "-s", "--format=%P", "HEAD").strip().split(),
        "commits": int(git(root, "rev-list", "--count", "HEAD")),
        "index": git(root, "ls-files", "--stage"),
        "status": git(root, "status", "--porcelain=v1", "--untracked-files=all"),
        "tree": git(root, "ls-tree", "-r", "HEAD"),
    }


def file_hash(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def source_hash(path: Path) -> str:
    return hashlib.sha256(path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()


def digest(value: object) -> str:
    data = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(data.encode()).hexdigest()


def snapshot(root: Path) -> dict:
    result = {}
    for base, dirs, files in os.walk(root, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d != ".git")
        for name in sorted(files + [d for d in dirs if (Path(base) / d).is_symlink()]):
            path = Path(base) / name
            key = path.relative_to(root).as_posix()
            if path.is_symlink():
                result[key] = {"symlink": os.readlink(path)}
            elif path.is_file():
                result[key] = {"bytes": path.stat().st_size, "sha256": file_hash(path)}
    return result


def write(root: Path, name: str, text: str) -> None:
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


